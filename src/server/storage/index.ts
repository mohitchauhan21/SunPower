import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { ValidationError } from "@/server/errors";

/**
 * File storage behind an interface. Dev uses local disk (./storage); an S3-compatible adapter
 * can be added later with the same interface and switched on with STORAGE_DRIVER=s3.
 */
export interface StorageProvider {
  put(key: string, bytes: Uint8Array, contentType: string): Promise<void>;
  get(key: string): Promise<Uint8Array>;
  delete(key: string): Promise<void>;
}

// ───────────────────────────── Upload policy ─────────────────────────────

export type UploadKind = "job-photo" | "signature" | "receipt" | "document";

export const UPLOAD_POLICY: Record<UploadKind, { maxBytes: number; types: readonly AllowedType[] }> = {
  "job-photo": { maxBytes: 8 * 1024 * 1024, types: ["image/jpeg", "image/png", "image/webp"] },
  signature: { maxBytes: 1 * 1024 * 1024, types: ["image/png"] },
  receipt: { maxBytes: 8 * 1024 * 1024, types: ["image/jpeg", "image/png", "image/webp", "application/pdf"] },
  document: { maxBytes: 15 * 1024 * 1024, types: ["application/pdf", "image/jpeg", "image/png"] },
};

export type AllowedType = "image/jpeg" | "image/png" | "image/webp" | "application/pdf";

const EXTENSION: Record<AllowedType, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "application/pdf": "pdf",
};

/** Identify a file by its first bytes — never trust the browser-supplied content type. */
export function sniffContentType(bytes: Uint8Array): AllowedType | null {
  const b = bytes;
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "image/jpeg";
  if (
    b.length >= 8 &&
    b[0] === 0x89 &&
    b[1] === 0x50 &&
    b[2] === 0x4e &&
    b[3] === 0x47 &&
    b[4] === 0x0d &&
    b[5] === 0x0a &&
    b[6] === 0x1a &&
    b[7] === 0x0a
  )
    return "image/png";
  if (
    b.length >= 12 &&
    b[0] === 0x52 &&
    b[1] === 0x49 &&
    b[2] === 0x46 &&
    b[3] === 0x46 &&
    b[8] === 0x57 &&
    b[9] === 0x45 &&
    b[10] === 0x42 &&
    b[11] === 0x50
  )
    return "image/webp";
  if (b.length >= 5 && b[0] === 0x25 && b[1] === 0x50 && b[2] === 0x44 && b[3] === 0x46 && b[4] === 0x2d)
    return "application/pdf";
  return null;
}

/** Check size and real file type against the policy. Returns the verified type and extension. */
export function validateUpload(
  kind: UploadKind,
  bytes: Uint8Array,
): { contentType: AllowedType; ext: string } {
  const policy = UPLOAD_POLICY[kind];
  if (bytes.length === 0) throw new ValidationError("The file is empty.");
  if (bytes.length > policy.maxBytes) {
    throw new ValidationError(
      `The file is too large. Maximum size is ${Math.round(policy.maxBytes / 1024 / 1024)} MB.`,
    );
  }
  const type = sniffContentType(bytes);
  if (!type || !policy.types.includes(type)) {
    throw new ValidationError(
      `This file type isn't allowed. Allowed: ${policy.types.map((t) => EXTENSION[t]).join(", ")}.`,
    );
  }
  return { contentType: type, ext: EXTENSION[type] };
}

/** Keys are generated by the server only: lowercase segments of [a-z0-9-_.], no traversal. */
const KEY_PATTERN = /^[a-z0-9][a-z0-9_-]*(\/[a-z0-9][a-z0-9_.-]*)*$/i;

export function assertSafeKey(key: string): void {
  if (!KEY_PATTERN.test(key) || key.includes("..") || key.length > 300) {
    throw new ValidationError("Invalid storage key.");
  }
}

// ───────────────────────────── Local disk ─────────────────────────────

export class LocalDiskStorage implements StorageProvider {
  private readonly root: string;

  constructor(rootDir: string) {
    this.root = path.resolve(rootDir);
  }

  private resolve(key: string): string {
    assertSafeKey(key);
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep)) throw new ValidationError("Invalid storage key.");
    return full;
  }

  async put(key: string, bytes: Uint8Array, _contentType?: string): Promise<void> {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, bytes);
  }

  async get(key: string): Promise<Uint8Array> {
    return new Uint8Array(await readFile(this.resolve(key)));
  }

  async delete(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }
}

let storage: StorageProvider | undefined;

export function getStorage(): StorageProvider {
  if (storage) return storage;
  const driver = process.env.STORAGE_DRIVER ?? "local";
  if (driver === "local") {
    storage = new LocalDiskStorage(process.env.STORAGE_LOCAL_DIR ?? "./storage");
    return storage;
  }
  throw new Error(`Unknown STORAGE_DRIVER "${driver}"`);
}
